import assert from 'node:assert/strict'
import {createRequire} from 'node:module'
import {readFileSync} from 'node:fs'
import {liveZoom,zoomSeconds,createLiveUpdater} from '../frontend/src/art/components/core/charts/art-line-chart/live-window.js'
const require=createRequire(new URL('../frontend/package.json',import.meta.url))
const echarts=require('echarts')
const chart=echarts.init(null,null,{renderer:'svg',ssr:true,width:1000,height:300})
const latest=1800000000000
const options=(now,span=180)=>({animation:false,xAxis:{type:'time',min:now-1800000,max:now},yAxis:{type:'value'},dataZoom:[liveZoom(now,span)],series:[{id:'live-power',type:'line',connectNulls:false,data:[[now-180000,1],[now-60000,null],[now-1000,0],[now,2]]}]})
try {
 chart.setOption(options(latest))
 assert.equal(zoomSeconds(chart.getOption().dataZoom[0]),180)
 assert.equal(chart.getOption().animation,false)
 let changed=0
 chart.on('datazoom',()=>changed++)
 chart.dispatchAction({type:'dataZoom',dataZoomId:'live-time-window',startValue:latest-600000,endValue:latest})
 const span=zoomSeconds(chart.getOption().dataZoom[0])
 assert.equal(span,600)
 assert.equal(changed,1)
 for(let i=1;i<=5;i++)chart.setOption(options(latest+i*1000,span))
 const next=chart.getOption()
 assert.equal(zoomSeconds(next.dataZoom[0]),600)
 assert.equal(next.dataZoom[0].endValue,latest+5000)
 assert.equal(next.series[0].data[1][1],null)
 assert.equal(next.series[0].data[2][1],0)
 assert.equal(next.dataZoom[0].zoomOnMouseWheel,true)
 assert.equal(liveZoom(latest,1).startValue,latest-15000)
 assert.equal(liveZoom(latest,9999).startValue,latest-1800000)
 assert.equal(zoomSeconds({}),null)
 const update=createLiveUpdater()
 const times=Array.from({length:1800},(_,i)=>latest/1000-1799+i)
 const values=times.map((_,i)=>i%19===0?null:1+i%5)
 const patch=update(times,values,180)
 assert.equal(patch.series[0].data.length,1800)
 assert.equal(update([...times],[...values],180),null,'duplicate snapshot must not redraw')
 assert.equal(update(times,values,600).dataZoom[0].startValue,latest-600000)
 values[100]=42
 assert.equal(update(times,values,600).series[0].data[100][1],42,'historical correction must redraw')
 chart.setOption({...options(latest),series:[{...options(latest).series[0],data:patch.series[0].data}]})
 assert.equal(chart.getOption().dataZoom[0].filterMode,'filter')
 const visible=chart.getModel().getSeriesByIndex(0).getData().count()
 assert.ok(visible<=181,`only visible 3-minute samples drawn, got ${visible}`)
 times.push(latest/1000+1);values.push(0)
 chart.setOption(update(times,values,180),{lazyUpdate:false,silent:true})
 assert.equal(chart.getOption().series[0].data.at(-1)[1],0)
 assert.equal(zoomSeconds(chart.getOption().dataZoom[0]),180)
 assert.equal(update([],[],180),null)
 const source=readFileSync(new URL('../frontend/src/art/components/core/charts/art-line-chart/index.vue',import.meta.url),'utf8')
 assert.match(source,/animation: !isLive.value/)
 assert.match(source,/if \(isLive.value && !isEmpty.value\)[\s\S]*?return/)
 assert.match(source,/lazyUpdate: true, silent: true/)
 assert.match(source,/document.hidden/)
 const hook=readFileSync(new URL('../frontend/src/art/hooks/core/useChart.ts',import.meta.url),'utf8')
 assert.match(hook,/const visibleOptions = pendingOptions\s+performChartInit\(visibleOptions\)/,'deferred chart must initialize axes and listeners before live patches')
 console.log('PASS: 180s default; wheel zoom retained; duplicate snapshots skipped; historical corrections; null/zero; 1800 retained / '+visible+' drawn; partial updates; hidden-tab guard')
} finally {chart.dispose()}
